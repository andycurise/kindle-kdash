// getDailyQuote 根据 quoteType 返回当天轮换的 Quote
func getDailyQuote(quoteType string, t time.Time) Quote {
	dayIndex := t.Year()*366 + t.YearDay()
	switch quoteType {
	case "poetry":
		idx := dayIndex % len(poetryQuotes)
		if idx < 0 {
			idx = -idx
		}
		return poetryQuotes[idx]
	case "famous":
		idx := dayIndex % len(famousQuotes)
		if idx < 0 {
			idx = -idx
		}
		return famousQuotes[idx]
	case "inspirational":
		idx := dayIndex % len(inspirationalQuotes)
		if idx < 0 {
			idx = -idx
		}
		return inspirationalQuotes[idx]
	default: // "mao"
		idx := dayIndex % len(maoQuotes)
		if idx < 0 {
			idx = -idx
		}
		return maoQuotes[idx]
	}
}

// dailyQuote 兼容旧调用
func dailyQuote(t time.Time) Quote {
	return getDailyQuote("mao", t)
}
